const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");
const context = vm.createContext({});
for (const name of ["import-format.js", "player-grades.js"]) vm.runInContext(fs.readFileSync(path.join(__dirname, "..", name), "utf8"), context);
const format = context.StatGMImportFormat;
const grade = context.StatGMGrades.describe;
assert.equal(format.extractGrade({ profile: { luckperms_primary_group: "cuivreii" }, grade: "rubis" }), "cuivreii");
assert.equal(format.extractGrade({ player: { grade: { name: "Diamant V" } } }), "Diamant V");
assert.equal(format.extractGrade({ rank: "modo" }), "modo");
assert.equal(format.extractGrade({ profile: { luckperms_primary_group: "" }, grade: "gerant" }), "gerant");
assert.equal(format.extractGrade({}), "");
assert.equal(grade("cuivre_2").src, "grades/cuivreii.png");
assert.equal(grade("§a§l[Émeraude V]").src, "grades/emeraudev.png");
assert.equal(grade("<green>Grade Fer III</green>").src, "grades/feriii.png");
assert.equal(grade("rank-diamant4").src, "grades/diamantiv.png");
assert.equal(grade("Super Modérateur").src, "grades/supermodo.png");
assert.equal(grade("Game Designer").src, "grades/gamedesigner.png");
assert.equal(grade("développeur").src, "grades/dev.png");
assert.equal(grade("grade_non_reconnu").src, null);
assert.equal(grade("grade_non_reconnu").label, "grade_non_reconnu");
assert.equal(grade("../../not-an-asset").src, null);
assert.equal(grade("").label, "Grade non renseigné");
const assets = fs.readdirSync(path.join(__dirname, "..", "grades")).filter(name => name.endsWith(".png"));
assert.equal(assets.length, 43);
for (const name of assets) assert.equal(grade(name.slice(0, -4)).src, `grades/${name}`);
console.log("PASS: grade extraction and priority, numeric/Roman tiers, accents, formatted grades, aliases, missing/unknown grades and all 43 provided assets.");
