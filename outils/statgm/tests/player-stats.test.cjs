const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const assert = require('node:assert/strict');
const context = vm.createContext({ Intl });
vm.runInContext(fs.readFileSync(path.join(__dirname, '../player-stats.js'), 'utf8'), context);
const stats = context.StatGMPlayerStats;
assert.equal(stats.number(0), '0');
assert.equal(stats.number(null), '—');
assert.equal(stats.number(undefined), '—');
assert.equal(stats.number(Infinity), '—');
assert.equal(stats.number(true), '—');
assert.equal(stats.duration(5086), '1 h 24 min');
assert.equal(stats.duration(0), '0 s');
assert.equal(stats.duration(null), '—');
assert.equal(stats.rank(0), 'Non renseigné');
assert.equal(stats.date(0), 'Non renseignée');
assert.equal(stats.date('2026-10-02T08:49:45.134549645'), '2 oct. 2026, 08:49');
assert.equal(stats.date('2026-10-02T08:49:45Z'), '2 oct. 2026, 10:49');
assert.equal(stats.fieldValue('online', false), 'Non');
assert.equal(stats.fieldValue('unknown', '<script>alert(1)</script>'), '<script>alert(1)</script>');
const input = { jobs_levels: { 'Bûcheron': 100 }, job_resources: { BUCHERON: [{ resource_key: 'oak_log', amount: 4, xp: 12, money: 0 }, { resource_key: 'grotte', amount: 0 }] }, rjobs_stats: [{ key: 'bucheron.oak_log', amount: 4, xp: 12, money: 0 }, { key: 'bucheron.cherry_log', amount: 8, xp: 24, money: 2 }], stats_store: { jobs_raw: { 'bucheron.oak_log': { amount: 900 } } } };
const original = JSON.stringify(input), jobs = stats.jobs(input);
assert.equal(jobs.length, 1); assert.equal(jobs[0].level, 100);
assert.equal(jobs[0].resources.length, 3);
assert.equal(stats.sum(jobs[0].resources, 'amount'), 12);
assert.equal(stats.sum(jobs[0].resources, 'xp'), 36);
assert.equal(stats.sum(jobs[0].resources, 'time_seconds'), null);
assert.equal(JSON.stringify(input), original, 'Presentation must not mutate imported data.');
const fixtureEconomy = {economy: {vault_gained_total_plugin: 70, vault_spent_total_plugin: 90, skript_sell_total_cumulative: 10, hopper_money_cumulative: 15, skript_sellstick_cumulative: 5, displayed_total_gained: 100}, stats_store: {economy: {gained_total: 700}}, plot: {bank: 999}, profile: {coins_skript: 999, vault_balance: 1}};
const economyBefore = JSON.stringify(fixtureEconomy), breakdown = stats.economy(fixtureEconomy);
assert.equal(breakdown.total, 70); assert.equal(breakdown.denominator, 70); assert.equal(breakdown.slices.length, 4);
assert.ok(Math.abs(breakdown.slices.reduce((sum, row) => sum + row.share, 0) - 100) < 1e-12);
assert.equal(breakdown.comparison[0].value, breakdown.total, 'The earned bar and donut center must use the same total without adding its categories.');
assert.equal(breakdown.comparison[0].label, 'Argent total gagné');
assert.equal(breakdown.comparison[0].source, 'economy.vault_gained_total_plugin');
assert.equal(breakdown.slices.find(row => row.key === 'other').value, 40);
assert.equal(breakdown.slices.find(row => row.key === 'other').label, 'Autres gains');
assert.equal(breakdown.slices.some(row => row.key === 'vault_gained_total_plugin' || row.key === 'earned'), false, 'The total must never be drawn as another category.');
assert.equal(breakdown.modules.length, 3);
assert.equal(breakdown.slices.find(row => row.key === 'hopper_money_cumulative').share, 15 / 70 * 100);
assert.equal(breakdown.comparison[0].value, 70);
assert.equal(breakdown.comparison[1].value, 90); assert.equal(breakdown.difference, -20);
assert.equal(JSON.stringify(fixtureEconomy), economyBefore, 'Charts must preserve the source and exclude wallets/plot/coins/raw copies.');
const noDeclared = {...fixtureEconomy, economy: {...fixtureEconomy.economy, displayed_total_gained: undefined}};
assert.equal(stats.economy(noDeclared).total, 70);
assert.equal(stats.economy(noDeclared).comparison[0].value, 70);
assert.equal(stats.economy({economy:{displayed_total_gained:100}}).comparison[0].value, null, 'Do not substitute the all-module total for a missing earned counter.');
const partial = stats.economy({economy:{displayed_total_gained:100, vault_gained_total_plugin:70}});
assert.equal(partial.slices.find(row => row.key === 'other').value, 70);
assert.equal(partial.slices.find(row => row.key === 'other').label, 'Gains non ventilés');
assert.equal(partial.partial, true);
assert.equal(partial.modules[1].value, null, 'Missing module values are not zero.');
assert.equal(stats.economy({economy:{vault_gained_total_plugin:70}}).total, 70, 'The authoritative total does not require category data.');
assert.equal(stats.economy({economy:{displayed_total_gained:30, skript_sell_total_cumulative:10, hopper_money_cumulative:15, skript_sellstick_cumulative:5}}).total, null, 'A category sum must never substitute for a missing total.');
assert.ok(stats.economy({economy:{vault_gained_total_plugin:10, skript_sell_total_cumulative:11}}).issue);
assert.equal(stats.economy({economy:{vault_gained_total_plugin:10, skript_sell_total_cumulative:11}}).slices.length, 0);
assert.ok(stats.economy({economy:{vault_gained_total_plugin:-1}}).issue);
assert.ok(stats.economy({economy:{vault_gained_total_plugin:10, skript_sell_total_cumulative:-1}}).issue);
assert.ok(stats.economy({economy:{vault_gained_total_plugin:0, skript_sell_total_cumulative:.005}}).issue);
const zeroEconomy = stats.economy({economy:{displayed_total_gained:0, vault_gained_total_plugin:0, vault_spent_total_plugin:0, skript_sell_total_cumulative:0, hopper_money_cumulative:0, skript_sellstick_cumulative:0}});
assert.equal(zeroEconomy.total, 0); assert.equal(zeroEconomy.difference, 0); assert.equal(zeroEconomy.slices.length, 0); assert.equal(zeroEconomy.issue, '');
assert.equal(stats.economy({}).total, null); assert.equal(stats.economy({}).difference, null);
const rounding = stats.economy({economy:{displayed_total_gained:.6, vault_gained_total_plugin:.3, skript_sell_total_cumulative:.1, hopper_money_cumulative:.2, skript_sellstick_cumulative:0}});
assert.equal(rounding.issue, ''); assert.ok(Math.abs(rounding.slices.reduce((sum, row) => sum + row.share, 0) - 100) < 1e-12);
const unusual = { nullable: null, enabled: false, zero: 0, list: [1, { unknown_future_field: 'retained' }], empty: [] };
const flattened = [...stats.leaves(unusual)];
assert.equal(flattened.length, 6);
assert.equal(flattened.find(row => row.key === 'unknown_future_field').path.join('.'), 'list.1.unknown_future_field');
assert.equal(flattened.find(row => row.key === 'zero').value, 0);
assert.equal(flattened.find(row => row.key === 'enabled').value, false);
let nested = { value: 42 }; for (let i = 0; i < 1500; i++) nested = { child: nested };
assert.equal([...stats.leaves(nested)][0].value, 42, 'Deep JSON should not overflow recursion.');
if (process.argv[2]) {
  const actual = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));
  const before = JSON.stringify(actual), actualJobs = stats.jobs(actual);
  assert.equal(actualJobs.length, 4); assert.equal(actual.player.name, 'zRynex_');
  assert.equal(actual.profile.vault_balance, 173809.97350000002);
  assert.equal(stats.duration(actual.playtime.play_seconds), '1 h 24 min');
  assert.equal(actual.quests.successes_completed, 58);
  assert.equal(actual.quests.successes_total, 67);
  assert.equal(actualJobs.find(job => job.key === 'bucheron').resources.find(row => row.resource_key === 'cherry_log').amount, 105839);
  assert.equal(actualJobs.find(job => job.key === 'fermier').resources.find(row => row.resource_key === 'nether_wart').amount, 1487366);
  const sum = actual.economy.vault_gained_total_plugin + actual.economy.skript_sell_total_cumulative + actual.economy.hopper_money_cumulative + actual.economy.skript_sellstick_cumulative;
  assert.ok(Math.abs(sum - actual.economy.displayed_total_gained) < 0.01);
  const economy = stats.economy(actual);
  assert.equal(economy.issue, ''); assert.equal(economy.total, actual.economy.vault_gained_total_plugin); assert.equal(economy.slices.length, 4);
  assert.equal(economy.comparison[0].value, economy.total);
  const categorySum = actual.economy.skript_sell_total_cumulative + actual.economy.hopper_money_cumulative + actual.economy.skript_sellstick_cumulative;
  assert.equal(economy.slices.find(row => row.key === 'other').value, economy.total - categorySum);
  assert.ok(Math.abs(economy.slices.reduce((sum, row) => sum + row.value, 0) - economy.total) < .01);
  assert.ok(Math.abs(economy.comparison[0].value - 82387529157.328) < .01);
  assert.ok(Math.abs(economy.difference + 58755961.47199) < .01);
  assert.ok(Math.abs(economy.slices.reduce((sum, row) => sum + row.share, 0) - 100) < 1e-10);
  assert.equal(JSON.stringify(actual), before);
  console.log(`PASS: provided player export; ${[...stats.leaves(actual)].length} original fields retained, four jobs, additional rJobs resources, earned total shared by both charts and categories counted once.`);
}
console.log('PASS: missing vs zero/false, dates and unzoned timestamps, duration/rank sentinels, source deduplication, unknown/deep fields and immutable model.');
